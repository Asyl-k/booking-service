CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES resources (id),
    customer_name VARCHAR(120) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT ck_bookings_interval CHECK (ends_at > starts_at),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);

-- Half-open intervals [starts_at, ends_at) allow back-to-back bookings while
-- rejecting overlaps. The partial predicate frees the slot after cancellation.
ALTER TABLE bookings
    ADD CONSTRAINT ex_bookings_confirmed_no_overlap
    EXCLUDE USING gist (
        resource_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    )
    WHERE (status = 'CONFIRMED');

CREATE INDEX idx_bookings_resource_starts ON bookings (resource_id, starts_at);
CREATE INDEX idx_bookings_customer ON bookings (customer_name);
